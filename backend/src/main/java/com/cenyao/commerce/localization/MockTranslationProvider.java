    private static void putPairs(String simplified, String traditional) {
        int n = Math.min(simplified.length(), traditional.length());
        for (int i = 0; i < n; i++) {
            CN_TO_TW.put(simplified.charAt(i), traditional.charAt(i));
        }
    }

    @Override
    public String providerCode() {
        return "MOCK";
    }

    @Override
    public String translate(String text, String sourceLang, String targetLang) {
        if (text == null) {
            return null;
        }
        if (targetLang == null || targetLang.equalsIgnoreCase(sourceLang)
                || "zh-CN".equalsIgnoreCase(targetLang) || "zh".equalsIgnoreCase(targetLang)) {
            return text;
        }
        log.info("【Stub】翻译提供方 MOCK：{} → {}，长度={}", sourceLang, targetLang, text.length());
        if ("zh-TW".equalsIgnoreCase(targetLang) || "zh-HK".equalsIgnoreCase(targetLang)) {
            return toTraditional(text);
        }
        return "[" + targetLang + "] " + text;
    }

    private static String toTraditional(String text) {
        StringBuilder sb = new StringBuilder(text.length());
        for (int i = 0; i < text.length(); i++) {
            char c = text.charAt(i);
            sb.append(CN_TO_TW.getOrDefault(c, c));
        }
        return sb.toString();
    }
